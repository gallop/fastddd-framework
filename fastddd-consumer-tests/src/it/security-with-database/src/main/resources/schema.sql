-- ECO-006C2：消费者自建 sys_audit_log（真实项目惯例——DDL 由消费者/迁移工具管理）。
-- 说明：框架 AuditLogServiceImpl#buildCreateTableSql 的自动建表走 MySqlDialect
-- （H2 无专用方言，AUTO_INCREMENT/TINYINT(1)/ENGINE 表选项在 H2 默认模式下不兼容），
-- 且其 method 列宽 VARCHAR(10) 小于切面写入的 "Class.method" 格式——两处为既有实现限制，
-- 已登记为 ECO-006C2 发现项，不在本批修改生产代码。此处按 INSERT 所需列结构自建表。
CREATE TABLE IF NOT EXISTS sys_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50),
    operation VARCHAR(200),
    operation_type VARCHAR(50),
    method VARCHAR(200),
    request_url VARCHAR(500),
    request_params CLOB,
    result CLOB,
    client_ip VARCHAR(50),
    user_agent VARCHAR(500),
    execution_time BIGINT,
    success BOOLEAN DEFAULT TRUE,
    error_message CLOB,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
